#!/usr/bin/env node
/**
 * Generates src/app/icons/backfilled.tsx: every icon the app imports from
 * @glacier/icons, re-exported pre-wrapped in the kit's IconBackfill.
 *
 * EXPLICIT NAMED IMPORTS, not `export * from`. A barrel that re-exports the
 * whole icon package pulls all ~1500 lucide glyphs into the bundle, because
 * there is nothing left for the bundler to tree-shake against. Listing only
 * what the app actually uses keeps the import graph exactly as narrow as it
 * was before the wrap.
 *
 * Regenerate after adding a new icon: `node scripts/gen-backfilled-icons.mjs`.
 * An icon that is missing from this file still works - it simply renders as a
 * plain outline, which is a visible inconsistency rather than a broken build.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const SRC = 'src/app';
const OUT = 'src/app/icons/backfilled.tsx';

function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const path = join(dir, entry);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const names = new Set();
for (const file of walk(SRC)) {
  if (!/\.tsx?$/.test(file) || file.endsWith('backfilled.tsx')) continue;
  const source = readFileSync(file, 'utf8');
  // BOTH sources. Once the codemod has pointed the app at this file, scanning
  // only for '@glacier/icons' finds almost nothing and a regenerate would empty
  // the module out from under every import that depends on it.
  for (const match of source.matchAll(/import\s*\{([^}]+)\}\s*from\s*'(?:@glacier\/icons|[^']*icons\/backfilled\.tsx)'/gs)) {
    for (const part of match[1].split(',')) {
      const name = part.trim().split(/\s+as\s+/)[0].trim();
      // Components only: the package also exports types and ICON_NAMES.
      if (/^[A-Z]/.test(name) && name !== 'IconProps') names.add(name);
    }
  }
}

const sorted = [...names].sort();
const body = `/* GENERATED by scripts/gen-backfilled-icons.mjs - do not edit by hand. */
import { createElement, type ComponentType } from 'react';
import { IconBackfill } from '@glacier/react';
import type { IconProps } from '@glacier/icons';
import {
${sorted.map((n) => `  ${n} as ${n}Outline,`).join('\n')}
} from '@glacier/icons';

/**
 * Every icon the app uses, pre-wrapped in IconBackfill.
 *
 * IconBackfill stacks a 33%-opacity silhouette of the glyph behind its own
 * outline, painted from the RESOLVED icon colour - so a muted icon backfills
 * muted and a custom-coloured one keeps its colour, rather than everything
 * turning accent.
 *
 * Wrapped here rather than at 600-odd call sites: the wrapper takes the same
 * props the bare icon did, so \`<Swords size={15} />\` is unchanged at every
 * one of them and the only edit per file is the import path.
 *
 * ONE DOM CHANGE TO KNOW ABOUT. The rendered node is now a <span> containing
 * two <svg>s, where it used to be a lone <svg>. Descendant selectors are fine;
 * a \`> svg\` child selector aimed at an icon is not, and the three the app had
 * were rewritten when this landed.
 */
function backfilled(Icon: ComponentType<IconProps>, name: string) {
  const Wrapped = ({ className, style, size, color, ...rest }: IconProps) =>
    createElement(
      IconBackfill,
      // Layout classes belong on the wrapper: it is the box now, and a class
      // put on the inner glyph would style one of two stacked copies.
      // children goes in the props object rather than as a third argument:
      // IconBackfillProps types it as a single element, and createElement's
      // variadic children widen to ReactNode[], which does not satisfy it.
      {
        // A stable hook on every backfilled icon. The rendered node is a span,
        // not an svg, so any CSS that reached an icon as a direct child needs
        // something to aim at that is not an element name - see .pcIcon in
        // cardpopup.css and table.css.
        className: className ? \`pcIcon \${className}\` : 'pcIcon',
        style,
        size,
        color,
        children: createElement(Icon, { size, color, ...rest }),
      },
    );
  Wrapped.displayName = \`Backfilled(\${name})\`;
  return Wrapped;
}

${sorted.map((n) => `export const ${n} = backfilled(${n}Outline, '${n}');`).join('\n')}
`;

writeFileSync(OUT, body);
console.log(`wrote ${OUT} with ${sorted.length} icons`);
